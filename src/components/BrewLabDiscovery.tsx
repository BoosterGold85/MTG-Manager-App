import { useEffect, useMemo, useRef, useState } from 'react';
import type { CardMetadata, CollectionState } from '../models/collection';
import type { Deck } from '../models/deck';
import { fingerprint } from '../experimental/universal/compiler';
import { ANALYZER_VERSION } from '../experimental/universal/protocol';
import { DIMENSION_TEXT, ROLE_TEXT } from '../experimental/universal/discovery';
import type { DiscoveryFinding, DiscoveryResult } from '../experimental/universal/discovery';
import { DiscoveryClient } from '../experimental/universal/discoveryClient';
import { discoveryInput } from '../experimental/universal/discoveryInput';

const MAX_CARDS_PER_PASS = 300;
type Row = { card: CardMetadata; result?: DiscoveryResult; error?: string };

/** Automatic discovery pass. Read-only: builds hypothetical scenarios, never edits the deck,
 * collection, scores or rankings, and keeps nothing after the Lab closes. */
export function BrewLabDiscovery({ state, deck, focus, onInspect }: { state: CollectionState; deck: Deck; focus?: CardMetadata; onInspect?: (id: string) => void }) {
  const input = useMemo(() => discoveryInput(state, deck), [state, deck]);
  const targets = useMemo(() => focus ? [focus] : input.candidates.slice(0, MAX_CARDS_PER_PASS), [focus, input]);
  const [rows, setRows] = useState<Row[] | null>(null), [running, setRunning] = useState(false), [done, setDone] = useState(0), [note, setNote] = useState('');
  const client = useRef<DiscoveryClient | null>(null), serial = useRef(0);
  const stop = () => { ++serial.current; client.current?.cancel(); };
  useEffect(() => () => { ++serial.current; client.current?.cancel(); }, []);
  const run = async () => {
    stop(); const token = serial.current, next: Row[] = [];
    setRows([]); setDone(0); setNote(''); setRunning(true);
    client.current ||= new DiscoveryClient();
    for (const card of targets) {
      const inDeck = input.deckCards.some(c => c.scryfallId === card.scryfallId);
      const cards = inDeck ? input.deckCards : [...input.deckCards, card];
      try {
        const result = await client.current.run({ revision: fingerprint([ANALYZER_VERSION, deck.id, input.revision, card.scryfallId]), cards, focusId: card.scryfallId, anchorIds: input.anchorIds, partnerIds: input.partnerIds, library: 40 });
        if (token !== serial.current) return;
        next.push({ card, result });
      } catch (error) {
        if (token !== serial.current || error instanceof DOMException && error.name === 'AbortError') return;
        next.push({ card, error: error instanceof Error ? error.message : 'Discovery failed.' });
      }
      setRows([...next]); setDone(next.length);
    }
    if (token === serial.current) setRunning(false);
  };
  const cancel = () => { stop(); setRunning(false); setNote('Discovery cancelled. Results so far are kept on screen; saved data is unchanged.'); };
  const found = (rows || []).filter(r => r.result?.findings.length), reach = (r: Row) => new Set(r.result!.findings.flatMap(f => f.partners.map(p => p.id))).size;
  // Display order only: chains witnessed with more deck cards first. Not a score or a ranking of value.
  const ordered = [...found].sort((a, b) => reach(b) - reach(a) || a.card.name.localeCompare(b.card.name));
  const unread = (rows || []).filter(r => r.result && !r.result.findings.length && r.result.interpretation.unsupported.length > 0);
  const quiet = (rows || []).filter(r => r.result && !r.result.findings.length && !r.result.interpretation.unsupported.length);
  const failed = (rows || []).filter(r => r.error);
  const label = focus ? `Find chains for ${focus.name} automatically` : `Find chains for my owned candidates (${targets.length})`;
  return <section aria-label={focus ? 'Automatic chain discovery for this card' : 'Automatic chain discovery'}>
    <h4>{focus ? 'Automatic discovery for this card' : 'Automatic discovery · what your owned cards do in this deck'}</h4>
    <p>{focus ? 'Tries this card' : 'Tries each owned candidate'} beside {input.anchorIds.length ? 'your commander and ' : ''}every deck card, then repeats each test without it. Only what the combination adds beyond the cards apart is reported. Mana to cast the cards in hand is assumed, never generated by the deck.</p>
    {!focus && <p className="meta-text">{input.candidates.length} owned nonland candidates not already in this deck{input.outsideIdentity ? ` · ${input.outsideIdentity} left out for being outside your commander's color identity` : ''}{input.candidates.length > MAX_CARDS_PER_PASS ? ` · first ${MAX_CARDS_PER_PASS} by name in this pass` : ''}.</p>}
    <button className="management-button" disabled={running || !targets.length} onClick={() => void run()}>{label}</button>
    {running && <button className="management-button" onClick={cancel}>Cancel discovery</button>}
    {running && <p role="status">Testing {Math.min(done + 1, targets.length)} of {targets.length} in an isolated worker…</p>}
    {note && <p role="alert">{note}</p>}
    {rows && !running && <div aria-label="Automatic discovery results">
      <p><strong>{found.length} of {rows.length} {rows.length === 1 ? 'card has' : 'cards have'} a witnessed chain.</strong> Provisional mechanical evidence in hypothetical scenarios — not a score, a ranking of value, or a claim about real games. {found.length > 1 ? 'Listed by how many deck cards completed a chain.' : ''}</p>
      {ordered.map(row => <article key={row.card.scryfallId} aria-label={`Chains for ${row.card.name}`}>
        <h4>{row.card.name}</h4>
        {row.result!.findings.map((finding, i) => <Finding key={i} name={row.card.name} finding={finding} />)}
        <Limits result={row.result!} />
        {onInspect && <button className="management-button" onClick={() => onInspect(row.card.scryfallId)}>Compare {row.card.name} with the original Brew Engine</button>}
      </article>)}
      {focus && !found.length && rows[0]?.result && <><p>No chain was witnessed for {focus.name} in this bounded pass. This does not establish that it lacks synergy here.</p><Limits result={rows[0].result} /></>}
      {!focus && unread.length > 0 && <details><summary>Not readable yet — Unknown, not weak ({unread.length})</summary><p>These cards have text the experimental engine cannot interpret, so no chain could be tested. This says nothing about their value.</p><ul>{unread.map(r => <li key={r.card.scryfallId}>{r.card.name} — {r.result!.interpretation.unsupported[0]}</li>)}</ul></details>}
      {!focus && quiet.length > 0 && <details><summary>Readable, no chain witnessed ({quiet.length})</summary><p>No supported chain was found in this bounded pass. Deck cards the engine cannot read were not testable partners, so this is not proof of no synergy.</p><ul>{quiet.map(r => <li key={r.card.scryfallId}>{r.card.name}</li>)}</ul></details>}
      {failed.length > 0 && <details><summary>Could not be tested ({failed.length})</summary><ul>{failed.map(r => <li key={r.card.scryfallId}>{r.card.name} — {r.error}</li>)}</ul></details>}
    </div>}
  </section>;
}

const list = (names: string[]) => names.length <= 2 ? names.join(' and ') : `${names.slice(0, -1).join(', ')} and ${names.at(-1)}`;
function Finding({ name, finding }: { name: string; finding: DiscoveryFinding }) {
  const adds = finding.gains.map(g => `+${g.added} ${DIMENSION_TEXT[g.dimension]}`).join(', ');
  const others = finding.required.map(r => r.name);
  const mana = Object.entries(finding.example.mana).filter(([, n]) => n > 0).map(([c, n]) => `${c} ${n}`).join(', ') || 'none';
  return <div>
    <p><strong>Adds {adds}</strong>{others.length ? <> with {list(others)}</> : null} — {name} {ROLE_TEXT[finding.role]}.</p>
    {finding.partners.length > 0 && <p>Witnessed separately with {finding.partners.length} deck {finding.partners.length === 1 ? 'card' : 'cards'}: {finding.partners.map(p => p.name).join(' · ')}{finding.partnersTruncated ? ' · and more' : ''}.</p>}
    <details><summary>How it works and what was assumed</summary>
      <ul>{finding.evidence.map(line => <li key={line}>{line}</li>)}{finding.branches.map(line => <li key={line}>Branch outcome — {line}</li>)}</ul>
      {finding.gains.map(g => <p key={g.dimension}>{DIMENSION_TEXT[g.dimension]}: {g.withFocus} together · {g.withoutFocus} in the same scenario without {name} · {g.focusAlone} from {name} alone.</p>)}
      <p>Example scenario: {finding.example.placements.map(p => `${p.name} (${p.zone})`).join(' · ')}. Assumed mana: {mana}. Only these cards were present; one modeled opponent, no responses. Other costs, timing and how often you assemble this are not estimated.</p>
    </details>
  </div>;
}
function Limits({ result }: { result: DiscoveryResult }) {
  return <p className="meta-text">{result.scenariosRun} scenarios tested · {result.partnersNotTestable} of {result.partnersConsidered} deck cards have text the engine cannot read and were not testable partners{result.truncated ? ' · search truncated — incomplete' : ''}{result.interpretation.unsupported.length ? ` · ${result.interpretation.unsupported.length} Unknown clause(s) on this card` : ''}.{result.reasons.map(r => ` ${r}`).join('')}</p>;
}
